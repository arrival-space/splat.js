// bake-model.mjs — a Blender model (scripts/blender/<id>.py → data/model/<id>.json) packed into
// the module the vibe ships with: src/render/data/<id>Model.js (the Extra 300L, the F-15C).
//
//   node scripts/bake-model.mjs [extra300l | f15c | data/model/<id>.json]
//
// Layout (little-endian): u32 header length, header JSON (part list with counts), padding to 4,
// then three streams: positions Int16 (1/posScale m, body axes: 1/4096 for the Extra's ±8 m, 1/2048 for
// the F-15's ±11 m), indices Uint16 per part, normals Int8 (·127).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const POS_SCALE = 4096;

export function packModel(model, posScale = POS_SCALE) {
  const parts = model.parts.map((p) => {
    const nv = p.positions.length / 3, ni = p.indices.length;
    if (nv >= 65536) throw new Error(`${p.name}: ${nv} vertices, more than a Uint16 index can reach`);
    const { positions, normals, indices, ...meta } = p;
    return { ...meta, nv, ni };
  });
  const header = new TextEncoder().encode(JSON.stringify(posScale === POS_SCALE ? { eye: model.eye, parts } : { eye: model.eye, posScale, parts }));
  const nvAll = parts.reduce((s, p) => s + p.nv, 0), niAll = parts.reduce((s, p) => s + p.ni, 0);
  const head = 4 + header.length, pad = (4 - (head % 4)) % 4;
  const buf = new ArrayBuffer(head + pad + nvAll * 6 + niAll * 2 + nvAll * 3);
  new DataView(buf).setUint32(0, header.length, true);
  new Uint8Array(buf, 4, header.length).set(header);
  const P = new Int16Array(buf, head + pad, nvAll * 3);
  const I = new Uint16Array(buf, head + pad + nvAll * 6, niAll);
  const N = new Int8Array(buf, head + pad + nvAll * 6 + niAll * 2, nvAll * 3);
  let pv = 0, pi = 0;
  for (const p of model.parts) {
    for (let k = 0; k < p.positions.length; k++) {
      const q = Math.round(p.positions[k] * posScale);
      if (Math.abs(q) > 32767) throw new Error(`${p.name}: coordinate ${p.positions[k]} out of range`);
      P[pv * 3 + k] = q;
      N[pv * 3 + k] = Math.round(Math.max(-1, Math.min(1, p.normals[k])) * 127);
    }
    I.set(p.indices, pi);
    pv += p.positions.length / 3;
    pi += p.indices.length;
  }
  return new Uint8Array(buf);
}

// which airplane: its JSON, the module it is baked into, the constant the module exports
const MODELS = {
  extra300l: { script: 'extra300l.py', out: 'extra300lModel.js', name: 'EXTRA300L_MODEL' },
  f15c: { script: 'f15c.py', out: 'f15cModel.js', name: 'F15C_MODEL', posScale: 2048 },
};

function main() {
  // node scripts/bake-model.mjs [extra300l | f15c | path/to/<id>.json]
  const arg = process.argv[2] || 'extra300l';
  const id = arg.replace(/^.*\//, '').replace(/\.json$/, '');
  const m = MODELS[id];
  if (!m) throw new Error(`unknown model ${id}: one of ${Object.keys(MODELS).join(', ')}`);
  const src = arg.endsWith('.json') ? arg : join(ROOT, 'data', 'model', `${id}.json`);
  const bytes = packModel(JSON.parse(readFileSync(src, 'utf8')), m.posScale);
  const b64 = Buffer.from(bytes).toString('base64');
  const out = join(ROOT, 'src', 'render', 'data', m.out);
  writeFileSync(out, `// Generated by scripts/bake-model.mjs from the Blender model (scripts/blender/${m.script}). Do not edit.\nexport const ${m.name} = '${b64}';\n`);
  console.log(`${(bytes.length / 1024).toFixed(0)} KB → ${(b64.length / 1024).toFixed(0)} KB base64 → ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
