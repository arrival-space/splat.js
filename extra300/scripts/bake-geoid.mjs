// bake-geoid.mjs — the geoid's height above the WGS-84 ellipsoid (EGM96, via the egm96-universal
// package), on a 1° grid, for the airfields found by name (src/world/airfields.js): Google's 3D tiles
// are in ellipsoid heights, an airfield's elevation is above sea level. Whole metres, Int8, rows from
// 90° S, columns from 180° W (361 of them: the seam repeated), gzipped, base64.
//
//   node scripts/bake-geoid.mjs   → src/world/data/geoid.js
import { gzipSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const egm96 = require('egm96-universal');
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const W = 361, H = 181, g = new Int8Array(W * H);
let worst = 0;
for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) {
  const v = egm96.meanSeaLevel(Math.max(-89.999, Math.min(89.999, j - 90)), i - 180);
  g[j * W + i] = Math.round(v);
  worst = Math.max(worst, Math.abs(v));
}
const b64 = gzipSync(Buffer.from(g.buffer), { level: 9 }).toString('base64');
writeFileSync(join(ROOT, 'src', 'world', 'data', 'geoid.js'), `// Generated by scripts/bake-geoid.mjs — EGM96 geoid heights above the WGS-84 ellipsoid (m), 1° grid,
// Int8, rows from 90° S, columns from 180° W (${W}×${H}), gzip, base64. EGM96: NGA, public domain.
export const GEOID = { w: ${W}, h: ${H}, b64: '${b64}' };
`);
console.log(`geoid: ${W}×${H}, |N| up to ${worst.toFixed(1)} m, ${(b64.length / 1024).toFixed(0)} KB`);
