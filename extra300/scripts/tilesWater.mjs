/** @returns {{ src: string, ok: boolean }} */
export function patchTilesWater(src) {
  let out = src;
  for (const p of PATCHES) {
    if (p.after != null) {
      if (out.split(p.after).length !== 2) return { src, ok: false };
      const i = out.indexOf(p.after) + p.after.length;
      out = `${out.slice(0, i)}\n${p.insert}${out.slice(i)}`;
    } else {
      if (out.split(p.replace).length !== 2) return { src, ok: false };
      out = out.replace(p.replace, () => p.with);
    }
  }
  return { src: out, ok: true };
}
