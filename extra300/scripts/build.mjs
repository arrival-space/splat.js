// build.mjs — bundle src/plugin/extra300.js and everything it imports into
// one ES module, the deliverable Arrival.Space loads as a vibe; and the airport
// and airplane vibes (plugin/airportVibe.js, plugin/aircraftVibe.js), small
// bundles of their own.
//
//   node scripts/build.mjs            → dist/extra300-meigs.mjs, dist/flight-airport.mjs, dist/flight-aircraft.mjs
//   node scripts/build.mjs --watch    → rebuild on change
//
// `ArrivalScript`, `ArrivalSpace` and `pc` stay free identifiers: the client
// provides them as globals at runtime.
import { build, context } from 'esbuild';
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
let rev = 'dev';
try { rev = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim(); } catch { /* not a checkout */ }

export const OUT = join(root, 'dist', 'extra300-meigs.mjs');
/** The airport and airplane vibes: published name → source. */
export const VIBES = {
  'flight-airport': join(root, 'src', 'plugin', 'airportVibe.js'),
  'flight-aircraft': join(root, 'src', 'plugin', 'aircraftVibe.js'),
};

const options = {
  entryPoints: [join(root, 'src', 'plugin', 'extra300.js')],
  outfile: OUT,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: false,
  legalComments: 'none',
  banner: {
    js: `// Extra 300L at Meigs Field — Arrival.Space vibe, v${pkg.version} (${rev}).\n`
      + '// Generated by scripts/build.mjs from the sources in extra300/src — edit those, not this file.\n',
  },
  logLevel: 'info',
};

const all = [options, ...Object.entries(VIBES).map(([name, src]) => ({
  ...options,
  entryPoints: [src],
  outfile: join(root, 'dist', `${name}.mjs`),
  banner: {
    js: `// ${name} — an Arrival.Space vibe for the Extra 300L flight sim, v${pkg.version} (${rev}).\n`
      + '// Generated by scripts/build.mjs from the sources in extra300/src — edit those, not this file.\n',
  },
}))];

mkdirSync(join(root, 'dist'), { recursive: true });
if (process.argv.includes('--watch')) {
  for (const o of all) await (await context(o)).watch();
} else {
  for (const o of all) await build(o);
}
